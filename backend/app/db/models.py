"""SQLAlchemy 2.0 models for every table in the tech spec's schema.

Conventions:
- Primary keys are UUIDs generated by Postgres (`gen_random_uuid()`), so IDs in URLs
  are not guessable (this is a multi-tenant SaaS).
- Timestamps are timezone-aware and default to the database clock.
- "Enum-like" columns (status, ...) are plain strings guarded by a CHECK constraint.
  The allowed values live in the `StrEnum` classes below; we avoid native Postgres
  ENUMs because adding or removing a value needs awkward migrations.
"""

import enum
import uuid
from datetime import datetime
from typing import Any

from pgvector.sqlalchemy import Vector
from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    DateTime,
    Float,
    ForeignKey,
    Integer,
    LargeBinary,
    String,
    Text,
    UniqueConstraint,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship

EMBEDDING_DIM = 384  # bge-small-en-v1.5


class TicketStatus(enum.StrEnum):
    OPEN = "open"
    RUNNING = "running"
    COMPLETED = "completed"
    NEEDS_HUMAN_REVIEW = "needs_human_review"


class RunStatus(enum.StrEnum):
    PENDING = "pending"
    RUNNING = "running"
    PASSED = "passed"
    FAILED = "failed"
    NEEDS_HUMAN_REVIEW = "needs_human_review"  # retry cap (2) exhausted


class TestStatus(enum.StrEnum):
    __test__ = False  # stop pytest trying to collect this as a test class
    PASSED = "passed"
    FAILED = "failed"
    ERROR = "error"


def status_check(column: str, enum_cls: type[enum.StrEnum], name: str) -> CheckConstraint:
    """CHECK constraint limiting `column` to the values of `enum_cls`.

    Built from the enum so Python and the DB can't drift apart in a model. Alembic
    does not autogenerate CHECK constraints, so migrations repeat the values by hand
    (see 0002): when you change an enum, write a migration that swaps the constraint.
    """
    values = ", ".join(f"'{member.value}'" for member in enum_cls)
    return CheckConstraint(f"{column} IN ({values})", name=name)


class Base(DeclarativeBase):
    pass


def _pk() -> Mapped[uuid.UUID]:
    return mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )


def _created_at() -> Mapped[datetime]:
    return mapped_column(DateTime(timezone=True), server_default=func.now())


class User(Base):
    __tablename__ = "users"

    id: Mapped[uuid.UUID] = _pk()
    github_id: Mapped[int] = mapped_column(BigInteger, unique=True)
    email: Mapped[str | None] = mapped_column(String(320))
    created_at: Mapped[datetime] = _created_at()

    repo_connections: Mapped[list["RepoConnection"]] = relationship(
        back_populates="user", cascade="all, delete-orphan"
    )
    tickets: Mapped[list["Ticket"]] = relationship(back_populates="user")


class RepoConnection(Base):
    __tablename__ = "repo_connections"
    __table_args__ = (UniqueConstraint("user_id", "repo_full_name"),)

    id: Mapped[uuid.UUID] = _pk()
    user_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), index=True
    )
    repo_full_name: Mapped[str] = mapped_column(String(255))  # "owner/repo"
    # Ciphertext only. Encryption/decryption happens in app code (added with the
    # repo-connect flow); the DB never sees the plaintext token.
    installation_token: Mapped[bytes | None] = mapped_column(LargeBinary)
    connected_at: Mapped[datetime] = _created_at()

    user: Mapped[User] = relationship(back_populates="repo_connections")
    # Deleting a repo deletes its tickets and indexed chunks (DELETE /repos/{id}).
    tickets: Mapped[list["Ticket"]] = relationship(
        back_populates="repo_connection", cascade="all, delete-orphan"
    )
    code_chunks: Mapped[list["CodeChunk"]] = relationship(
        back_populates="repo_connection", cascade="all, delete-orphan"
    )


class Ticket(Base):
    __tablename__ = "tickets"
    __table_args__ = (status_check("status", TicketStatus, "ck_tickets_status"),)

    id: Mapped[uuid.UUID] = _pk()
    user_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), index=True
    )
    repo_connection_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("repo_connections.id", ondelete="CASCADE"), index=True
    )
    title: Mapped[str] = mapped_column(String(500))
    description: Mapped[str] = mapped_column(Text, default="")
    status: Mapped[str] = mapped_column(
        String(32), default=TicketStatus.OPEN, server_default=TicketStatus.OPEN.value
    )
    created_at: Mapped[datetime] = _created_at()

    user: Mapped[User] = relationship(back_populates="tickets")
    repo_connection: Mapped[RepoConnection] = relationship(back_populates="tickets")
    runs: Mapped[list["AgentRun"]] = relationship(
        back_populates="ticket", cascade="all, delete-orphan"
    )


class AgentRun(Base):
    __tablename__ = "agent_runs"
    __table_args__ = (status_check("status", RunStatus, "ck_agent_runs_status"),)

    id: Mapped[uuid.UUID] = _pk()
    ticket_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("tickets.id", ondelete="CASCADE"), index=True
    )
    status: Mapped[str] = mapped_column(
        String(32), default=RunStatus.PENDING, server_default=RunStatus.PENDING.value
    )
    started_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    finished_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    ticket: Mapped[Ticket] = relationship(back_populates="runs")
    steps: Mapped[list["AgentStep"]] = relationship(
        back_populates="run", cascade="all, delete-orphan", order_by="AgentStep.created_at"
    )
    test_results: Mapped[list["TestResult"]] = relationship(
        back_populates="run", cascade="all, delete-orphan"
    )


class AgentStep(Base):
    __tablename__ = "agent_steps"

    id: Mapped[uuid.UUID] = _pk()
    run_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("agent_runs.id", ondelete="CASCADE"), index=True
    )
    agent_name: Mapped[str] = mapped_column(String(64))
    # JSONB: each agent has a different input/output shape (plan, diff, tests, ...).
    input: Mapped[dict[str, Any] | None] = mapped_column(JSONB)
    output: Mapped[dict[str, Any] | None] = mapped_column(JSONB)
    tokens_used: Mapped[int | None] = mapped_column(Integer)
    latency_ms: Mapped[int | None] = mapped_column(Integer)
    created_at: Mapped[datetime] = _created_at()

    run: Mapped[AgentRun] = relationship(back_populates="steps")


class CodeChunk(Base):
    __tablename__ = "code_chunks"

    id: Mapped[uuid.UUID] = _pk()
    # Every retrieval query MUST filter on this, so tenants' code never mixes.
    repo_connection_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("repo_connections.id", ondelete="CASCADE"), index=True
    )
    file_path: Mapped[str] = mapped_column(Text)
    content: Mapped[str] = mapped_column(Text)
    embedding: Mapped[list[float]] = mapped_column(Vector(EMBEDDING_DIM))
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now()
    )

    repo_connection: Mapped[RepoConnection] = relationship(back_populates="code_chunks")


class TestResult(Base):
    __tablename__ = "test_results"
    __test__ = False  # not a pytest test class
    __table_args__ = (status_check("status", TestStatus, "ck_test_results_status"),)

    id: Mapped[uuid.UUID] = _pk()
    run_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("agent_runs.id", ondelete="CASCADE"), index=True
    )
    test_name: Mapped[str] = mapped_column(String(500))
    status: Mapped[str] = mapped_column(String(32))
    output: Mapped[str | None] = mapped_column(Text)
    created_at: Mapped[datetime] = _created_at()

    run: Mapped[AgentRun] = relationship(back_populates="test_results")


class BenchmarkRun(Base):
    __tablename__ = "benchmark_runs"

    id: Mapped[uuid.UUID] = _pk()
    model_name: Mapped[str] = mapped_column(String(255))
    quantization: Mapped[str | None] = mapped_column(String(64))  # e.g. "awq"; null for API
    avg_latency_ms: Mapped[float] = mapped_column(Float)
    throughput_tokens_per_sec: Mapped[float] = mapped_column(Float)
    cost_estimate: Mapped[float | None] = mapped_column(Float)
    created_at: Mapped[datetime] = _created_at()
