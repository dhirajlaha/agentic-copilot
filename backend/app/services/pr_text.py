"""The words that go on GitHub: branch name, commit message, pull request title and body.

Everything here is derived from text a user or a model wrote, and a pull request is visible to
other people, so it is neutralised first: an `@name` would notify a real account, and `<` could
inject HTML into the description. Lengths are capped so nothing can bloat the page.
"""

import re
from uuid import UUID

from app.agents.schemas import Patch

ZERO_WIDTH_SPACE = "\u200b"
_ACTIONS = {"modify": "modified", "create": "added", "delete": "deleted"}


def neutralise(text: str, limit: int) -> str:
    """Safe to place in markdown: capped, HTML-escaped, and mentions defused. The cap applies
    to the original text, before escaping, so the result can be somewhat longer."""
    text = text.replace("\r", "").strip()
    if len(text) > limit:
        text = text[: limit - 1].rstrip() + "…"
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return text.replace("@", "@" + ZERO_WIDTH_SPACE)


def _single_line(text: str, limit: int) -> str:
    """For titles and commit subjects: one line, no control characters, mentions defused.
    Not HTML-escaped: these are plain text, not rendered as markup."""
    collapsed = "".join(c for c in " ".join(text.split()) if ord(c) >= 32)
    collapsed = collapsed.replace("@", "@" + ZERO_WIDTH_SPACE)  # before capping, so the cap holds
    if len(collapsed) > limit:
        collapsed = collapsed[: limit - 1].rstrip() + "…"
    return collapsed


def _cell(text: str, limit: int) -> str:
    return neutralise(text, limit).replace("|", "\\|").replace("\n", " ")


def branch_name(ticket_title: str, run_id: UUID) -> str:
    """`copilot/<slug>-<first 8 of the run id>`: unique per run, so publishing never
    collides with, or overwrites, an earlier branch."""
    slug = re.sub(r"[^a-z0-9]+", "-", ticket_title.lower()).strip("-")[:40].strip("-")
    return f"copilot/{slug or 'change'}-{str(run_id)[:8]}"


def pr_title(ticket_title: str) -> str:
    return _single_line(ticket_title, 120) or "Change proposed by Agentic Copilot"


def commit_message(ticket_title: str, summary: str, run_id: UUID) -> str:
    subject = _single_line(ticket_title, 72) or "Change proposed by Agentic Copilot"
    body = _single_line(summary, 1000)
    return f"{subject}\n\n{body}\n\nGenerated by Agentic Copilot (run {run_id})."


def pr_body(
    *,
    ticket_title: str,
    patch: Patch,
    subtasks: list[tuple[str, str]],
    run_id: UUID,
) -> str:
    lines = ["## Summary", "", neutralise(patch.summary, 2000) or "(no summary)", ""]

    lines += ["## Changes", "", "| File | Change | Lines | Why |", "|---|---|---|---|"]
    for change in patch.changes:
        lines.append(
            f"| `{change.path}` | {_ACTIONS[change.action]} | "
            f"+{change.lines_added} -{change.lines_removed} | {_cell(change.reason, 300)} |"
        )
    lines.append("")

    if subtasks:
        lines += ["## Plan followed", ""]
        lines += [
            f"{i}. **{_cell(title, 200)}**: {_cell(details, 400)}"
            for i, (title, details) in enumerate(subtasks, start=1)
        ]
        lines.append("")

    if patch.open_questions:
        lines += ["## Open questions", ""]
        lines += [f"- {neutralise(q, 400)}" for q in patch.open_questions]
        lines.append("")

    lines += [
        "---",
        f"Generated by Agentic Copilot for the ticket “{neutralise(ticket_title, 200)}” "
        f"(run `{run_id}`), based on commit `{patch.base_commit_sha[:7]}`.",
        "",
        "**Tests were not run on this change.** Review it like any other pull request "
        "before merging.",
    ]
    return "\n".join(lines)
