def test_the_body_lists_summary_changes_and_the_tests_notice():
    text = body(subtasks=[("Fix parser", "Allow plus signs")])
    assert "## Summary\n\nStrip whitespace before parsing." in text
    assert "| `src/login.py` | modified | +3 -1 | Whitespace broke parsing. |" in text
    assert "1. **Fix parser**: Allow plus signs" in text
    assert "run `1a2b3c4d-0000-4000-8000-000000000000`" in text
    assert "commit `abcdef1`" in text
    assert "**Tests were not run on this change.**" in text


def test_actions_are_described_in_words():
    patch = make_patch(
        changes=[
            make_patch().changes[0].model_copy(update={"action": "create", "path": "a.py"}),
            make_patch().changes[0].model_copy(update={"action": "delete", "path": "b.py"}),
        ]
    )
    text = body(patch)
    assert "| `a.py` | added |" in text and "| `b.py` | deleted |" in text


def test_open_questions_appear_only_when_there_are_some():
    assert "## Open questions" not in body()
    text = body(make_patch(open_questions=["Which format?"]))
    assert "## Open questions\n\n- Which format?" in text


def test_untrusted_text_is_neutralised_everywhere_in_the_body():
    patch = make_patch(
        summary="Hi @victim <img src=x onerror=1>",
        open_questions=["ping @someone"],
    )
    patch.changes[0].reason = "x | y\n@admin"
    text = body(patch, title="Ticket by @attacker <b>", subtasks=[("T @a", "d | @b")])
    for mention in ("@victim", "@someone", "@admin", "@attacker", "@a ", "@b"):
        assert mention not in text.replace("@" + ZWSP, "") or mention not in text
    assert "<img" not in text and "<b>" not in text
    assert "x \\| y @" + ZWSP + "admin" in text  # pipes cannot break the table


def test_a_table_row_cannot_be_broken_by_a_reason_with_newlines_or_pipes():
    patch = make_patch()
    patch.changes[0].reason = "line1\n| fake | row |"
    rows = [line for line in body(patch).splitlines() if line.startswith("| `")]
    assert len(rows) == 1
