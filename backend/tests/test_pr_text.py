from uuid import UUID

import pytest

from app.agents.schemas import AppliedChange, EditOut, Patch
from app.services import pr_text

RUN = UUID("1a2b3c4d-0000-4000-8000-000000000000")
ZWSP = "​"


def make_patch(**overrides) -> Patch:
    change = AppliedChange(
        path="src/login.py",
        action="modify",
        reason="Whitespace broke parsing.",
        edits=[EditOut(search="a", replace="b")],
        content="",
        diff="--- a/src/login.py\n",
        lines_added=3,
        lines_removed=1,
    )
    values = {
        "base_commit_sha": "abcdef1234567890" * 2 + "abcdef12",
        "summary": "Strip whitespace before parsing.",
        "changes": [change],
        "open_questions": [],
        "attempts": 1,
        "files_changed": 1,
        "lines_added": 3,
        "lines_removed": 1,
    }
    return Patch(**{**values, **overrides})


def body(patch=None, title="Fix login", subtasks=()):
    return pr_text.pr_body(
        ticket_title=title, patch=patch or make_patch(), subtasks=list(subtasks), run_id=RUN
    )


# ---- neutralise ---------------------------------------------------------------------


def test_mentions_are_defused_so_nobody_is_notified():
    assert "@" + ZWSP + "octocat" in pr_text.neutralise("thanks @octocat", 100)
    assert "@octocat" not in pr_text.neutralise("thanks @octocat", 100)


def test_html_is_escaped():
    out = pr_text.neutralise("<script>alert(1)</script> & <!-- hidden -->", 200)
    assert "<" not in out and ">" not in out
    assert "&lt;script&gt;" in out and "&amp;" in out


def test_long_text_is_capped_with_an_ellipsis():
    out = pr_text.neutralise("x" * 500, 100)
    assert len(out) <= 100 and out.endswith("…")


# ---- branch, title, commit ----------------------------------------------------------


@pytest.mark.parametrize(
    ("title", "expected"),
    [
        ("Fix login bug", "copilot/fix-login-bug-1a2b3c4d"),
        ("  Weird!!  ###  Title  ", "copilot/weird-title-1a2b3c4d"),
        ("Ünïcödé 修复", "copilot/n-c-d-1a2b3c4d"),
        ("!!!", "copilot/change-1a2b3c4d"),
        ("", "copilot/change-1a2b3c4d"),
    ],
)
def test_branch_names_are_safe_and_unique_per_run(title, expected):
    assert pr_text.branch_name(title, RUN) == expected


def test_branch_names_are_bounded_and_only_use_safe_characters():
    name = pr_text.branch_name("a very long title " * 20, RUN)
    assert len(name) <= len("copilot/") + 40 + 9
    assert all(c.isalnum() or c in "/-" for c in name)
    assert ".." not in name and not name.endswith("/") and not name.endswith("-")


def test_two_runs_of_the_same_ticket_get_different_branches():
    other = UUID("ffffffff-0000-4000-8000-000000000000")
    assert pr_text.branch_name("Fix", RUN) != pr_text.branch_name("Fix", other)


def test_the_title_is_one_clean_line():
    title = pr_text.pr_title("Fix\nlogin\t bug\x00 for @user " + "x" * 300)
    assert "\n" not in title and "\x00" not in title and len(title) <= 120
    assert "@user" not in title


def test_an_empty_title_gets_a_default():
    assert pr_text.pr_title("  \n ") == "Change proposed by Agentic Copilot"


def test_commit_message_has_subject_body_and_provenance():
    message = pr_text.commit_message("Fix login", "Strips whitespace.", RUN)
    subject, blank, rest = message.split("\n", 2)
    assert subject == "Fix login" and blank == ""
    assert "Strips whitespace." in rest and f"Generated by Agentic Copilot (run {RUN})" in rest
    assert len(pr_text.commit_message("x" * 200, "s", RUN).split("\n")[0]) <= 72


